#!/usr/bin/env python3
"""Writes Tests/Shared/PreviewSmokeTests.generated.swift: one test per PreviewProvider under
Platform/Shared, Platform/macOS and Platform/iOS, each rendering its previews offscreen
through PreviewSmokeTestCase. Previews made with the #Preview macro cannot be enumerated
and are not listed. Usage: gen-preview-smoke.py [--check]   (--check only reports whether
the file is current)"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, "Tests", "Shared", "PreviewSmokeTests.generated.swift")
DIRECTORIES = {"Shared": None, "macOS": "os(macOS)", "iOS": "os(iOS)"}
# a shared file that imports one of these is compiled into the macOS app only
MACOS_ONLY_IMPORTS = ("Virtualization",)
PROVIDER = re.compile(r"^(?:private |fileprivate )?struct (\w+)\s*:\s*PreviewProvider", re.M)
ENVIRONMENT_OBJECT = re.compile(r"@EnvironmentObject[^:\n]*:\s*([\w.]+)")


def providers():
    found = []
    for directory, directory_condition in DIRECTORIES.items():
        folder = os.path.join(ROOT, "Platform", directory)
        for name in sorted(os.listdir(folder)):
            if not name.endswith(".swift"):
                continue
            condition = directory_condition
            source = open(os.path.join(folder, name), encoding="utf-8").read()
            if condition is None and re.search(r"^import (?:%s)$" % "|".join(MACOS_ONLY_IMPORTS), source, re.M):
                condition = "os(macOS)"
            needs = sorted(set(ENVIRONMENT_OBJECT.findall(source)))
            for match in PROVIDER.finditer(source):
                private = match.group(0).startswith(("private", "fileprivate"))
                found.append((match.group(1), f"Platform/{directory}/{name}", condition, private, needs))
    return found


